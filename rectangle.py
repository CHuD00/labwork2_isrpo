def area(a, b): 
    '''Принимает стороны прямоугольника, возвращает площадь этого прямоугольника
    Пример вызова: area(3, 5), вернёт 15
    '''
    return a * b 

def perimeter(a, b): 
    '''Принимает стороны прямоугольника, возвращает периметр этого прямоугольника
    Пример вызова: perimeter(3, 5), вернёт 16
        '''
    return 2*(a + b)
