import math


def area(r):
    '''Принимает радиус круга, возвращает площадь круга
    Пример вызова: area(5), вернёт 78.53981633974483
    '''
    return math.pi * r * r


def perimeter(r):
    '''Принимает радиус круга, возвращает длину окружности
    Пример вызова: perimeter(5), вернёт 31.41592653589793
    '''
    return 2 * math.pi * r

