def area(a, h): 
    '''Принимает сторону треугольника a и высоту опущенную на эту сторону, возвращает площадь треугольника
    Пример вызова: area(3, 6), вернёт 9
    '''
    return a * h / 2 

def perimeter(a, b, c): 
    '''Принимает стороны треугольника, возвращает его периметр
        Пример вызова: area(3, 5, 6), вернёт 14
        '''
    return a + b + c 
